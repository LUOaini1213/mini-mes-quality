"""Turn results/*.json into (a) results/headline.json, (b) the generated block in README.md and (c) a read-only
results/report.html. README numbers come only from here; tests/test_readme.py re-renders the block from results/
and checks that the README matches."""
from __future__ import annotations

import html
import io
import json
import re
from pathlib import Path

import pandas as pd

BEGIN, END = "<!-- RESULTS:BEGIN (generated by run_all.py - do not edit) -->", "<!-- RESULTS:END -->"

# Published reference numbers (image AUROC / pixel AUROC / AUPRO, percent) for the same categories and protocol
# family (one-class VisA, 256x256). Copied from the papers' tables; see README "Comparison with published results".
PUBLISHED = {
    "PatchCore (WRN50), He et al. 2024, MambaAD arXiv:2404.06564, Tab. A15/A16": {
        "pcb1": (97.7, 99.8, 94.7), "pcb4": (99.8, 98.2, 82.2)},
    "PaDiM (ResNet-50, supervised ImageNet), Zou et al. ECCV 2022 (VisA paper) Tab. 7/8": {
        "pcb1": (92.0, 97.3, None), "pcb4": (98.5, 88.4, None)},
}


def _load(p: Path):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def headline(results: Path) -> dict:
    h: dict = {}
    vis = _load(results / "vision" / "metrics.json")
    if vis:
        for cat, r in vis["categories"].items():
            for m, v in r["methods"].items():
                h[f"vision.{cat}.{m}.image_auroc"] = v["image_auroc"]
                if v["pixel_auroc"] is not None:
                    h[f"vision.{cat}.{m}.pixel_auroc"] = v["pixel_auroc"]
                    h[f"vision.{cat}.{m}.aupro"] = v["aupro_0_3"]
            t = r["methods"]["patchcore_lite"]["at_threshold"]
            h[f"vision.{cat}.patchcore_lite.test_tpr"] = t["tpr"]
            h[f"vision.{cat}.patchcore_lite.test_fpr"] = t["fpr"]
    mes = _load(results / "mes" / "trace_summary.json")
    if mes:
        for mode, s in mes["multi_seed"].items():
            h[f"mes.{mode}.n_seeds"] = s["n_seeds"]
            h[f"mes.{mode}.both_causes_recovered"] = s["both_causes_recovered"]
            for k, v in s["recovery_rate_by_cause"].items():
                h[f"mes.{mode}.recovered[{k}]"] = v
            h[f"mes.{mode}.seeds_with_false_lead_selected"] = s["seeds_with_false_lead_selected"]
            h[f"mes.{mode}.mean_false_leads_selected"] = s["mean_false_leads_selected"]
            h[f"mes.{mode}.mean_false_leads_screened_naive"] = s["mean_false_leads_screened_naive"]
            for k, v in s["trap_flagged_by_naive_screen"].items():
                h[f"mes.{mode}.trap_flagged_naive[{k}]"] = v
            for k, v in s["trap_selected_after_stratification"].items():
                h[f"mes.{mode}.trap_selected[{k}]"] = v
            h[f"mes.{mode}.mean_units"] = s["mean_units"]
            h[f"mes.{mode}.mean_inspection_tpr"] = s["mean_inspection_tpr"]
            h[f"mes.{mode}.mean_inspection_fpr"] = s["mean_inspection_fpr"]
    mut = _load(results / "mutation.json")
    if mut:
        h["tests.mutations_caught"] = mut["caught"]
        h["tests.mutations_total"] = mut["total"]
    sop = _load(results / "sop" / "sop_eval.json")
    if sop:
        for name, s in sop["systems"].items():
            a = s["answers_test"]
            h[f"sop.{name}.test_accuracy"] = a["accuracy"]
            h[f"sop.{name}.answerable_correct"] = a["answerable_correct"]
            h[f"sop.{name}.answerable_refused"] = a["answerable_refused"]
            h[f"sop.{name}.unanswerable_refused"] = a["unanswerable_refused"]
            for mode, r in s["retrieval_test"].items():
                h[f"sop.{name}.retrieval.{mode}.hit_at_1"] = r["hit_at_1"]
                h[f"sop.{name}.retrieval.{mode}.hit_at_3"] = r["hit_at_3"]
    return h


def pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}"


def readme_block(results: Path) -> str:
    vis = _load(results / "vision" / "metrics.json")
    mes = _load(results / "mes" / "trace_summary.json")
    sop = _load(results / "sop" / "sop_eval.json")
    L = [BEGIN, ""]
    if vis:
        L += ["### Visual inspection - VisA (real images), official one-class test split", "",
              "| Category | Method | Image AUROC | Pixel AUROC | AUPRO@0.3 | Test TPR / FPR at fixed threshold |",
              "|---|---|---|---|---|---|"]
        for cat, r in vis["categories"].items():
            for m, v in r["methods"].items():
                t = v["at_threshold"]
                L.append(f"| {cat} | {m} | {pct(v['image_auroc'])} | {pct(v['pixel_auroc'])} | {pct(v['aupro_0_3'])} "
                         f"| {pct(t['tpr'])} / {pct(t['fpr'])} |")
        L += ["", "Published reference numbers (percent, image AUROC / pixel AUROC / AUPRO):", ""]
        for src, d in PUBLISHED.items():
            L.append(f"- {src}: " + "; ".join(
                f"{c} {a} / {b} / {'n/a' if p is None else p}" for c, (a, b, p) in d.items()))
        L.append("")
    if mes:
        L += [f"### Traceability on synthetic MES data ({mes['multi_seed'][next(iter(mes['multi_seed']))]['n_seeds']} "
              "generator seeds)", "",
              "| Inspection mode | Both causes recovered | Drift cause | Bad-batch cause | Seeds with a false lead selected "
              "| Mean false leads, naive screen | Trap operator flagged naive / selected | Trap oven flagged naive / selected "
              "| Inspection TPR / FPR | Units per seed |",
              "|---|---|---|---|---|---|---|---|---|---|"]
        for mode, s in mes["multi_seed"].items():
            rc = s["recovery_rate_by_cause"]
            tf, ts = s["trap_flagged_by_naive_screen"], s["trap_selected_after_stratification"]
            keys = list(tf)
            L.append(f"| {mode} | {pct(s['both_causes_recovered'])}% | {pct(rc[mes['truth'][0]])}% | "
                     f"{pct(rc[mes['truth'][1]])}% | {pct(s['seeds_with_false_lead_selected'])}% | "
                     f"{s['mean_false_leads_screened_naive']:.2f} | {pct(tf[keys[0]])}% / {pct(ts[keys[0]])}% | "
                     f"{pct(tf[keys[1]])}% / {pct(ts[keys[1]])}% | {pct(s['mean_inspection_tpr'])} / "
                     f"{pct(s['mean_inspection_fpr'])} | {s['mean_units']:.0f} |")
        L.append("")
    if sop:
        L += ["### SOP assistant - held-out test questions (synthetic documents)", "",
              "| System | Test accuracy | Answerable: correct | Answerable: wrongly refused | Unanswerable: refused "
              "| Retrieval hit@1 / hit@3 (hybrid or BM25) |", "|---|---|---|---|---|---|"]
        for name, s in sop["systems"].items():
            a = s["answers_test"]
            r = s["retrieval_test"].get("hybrid", s["retrieval_test"]["bm25"])
            L.append(f"| {name} | {pct(a['accuracy'])}% ({a['n']} q) | {pct(a['answerable_correct'])}% | "
                     f"{pct(a['answerable_refused'])}% | {pct(a['unanswerable_refused'])}% | "
                     f"{pct(r['hit_at_1'])} / {pct(r['hit_at_3'])} |")
        L.append("")
    mut = _load(results / "mutation.json")
    if mut:
        L += ["### Test-suite mutation check", "",
              f"{mut['caught']} of {mut['total']} hand-made mutations of the source code are caught by the tests "
              "(`tools/mutation_test.py`, details in `results/mutation.json`).", ""]
    L.append(END)
    return "\n".join(L)


def update_readme(readme: Path, block: str) -> None:
    text = readme.read_text(encoding="utf-8")
    pat = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    if not pat.search(text):
        raise ValueError("README has no results markers")
    readme.write_text(pat.sub(lambda _: block, text), encoding="utf-8", newline="\n")


def _svg_weekly(results: Path) -> str:
    p = results / "mes" / "weekly_rates_seed7_detector.csv"
    if not p.exists():
        p = results / "mes" / "weekly_rates_seed7_simulated.csv"
    if not p.exists():
        return ""
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    df = pd.read_csv(p)
    fig, axes = plt.subplots(1, df.cause.nunique(), figsize=(10, 3.2), sharey=True)
    for ax, (cause, g) in zip(axes, df.groupby("cause", sort=False)):
        for exp, lab, col in [(1, "exposed", "#c2410c"), (0, "not exposed", "#64748b")]:
            d = g[(g.exposed == exp) & (g.n > 0)]
            ax.errorbar(d.week, 100 * d.rate, yerr=[100 * (d.rate - d.lo), 100 * (d.hi - d.rate)], marker="o",
                        capsize=3, label=lab, color=col)
        ax.set_title(cause, fontsize=9)
        ax.set_xlabel("week")
        ax.grid(alpha=0.3)
    axes[0].set_ylabel("AOI FAIL rate, % (95% Wilson CI)")
    axes[0].legend(fontsize=8)
    fig.tight_layout()
    buf = io.StringIO()
    fig.savefig(buf, format="svg")
    plt.close(fig)
    return buf.getvalue()[buf.getvalue().find("<svg"):]


def _table(df: pd.DataFrame) -> str:
    return df.to_html(index=False, escape=True, float_format=lambda x: f"{x:.4g}", border=0)


def write_html(results: Path) -> None:
    md = readme_block(results)
    rows, in_table = [], False
    for line in md.splitlines():
        is_row = line.startswith("|")
        if in_table and not is_row:
            rows.append("</table>")
            in_table = False
        if line.startswith("<!--") or line.startswith("|---"):
            continue
        if is_row:
            if not in_table:
                rows.append("<table>")
                in_table = True
            cells = [c.strip() for c in line.strip("|").split("|")]
            rows.append("<tr>" + "".join(f"<td>{html.escape(c)}</td>" for c in cells) + "</tr>")
        elif line.startswith("### "):
            rows.append(f"<h2>{html.escape(line[4:])}</h2>")
        elif line.startswith("- "):
            rows.append(f"<p class=ref>{html.escape(line[2:])}</p>")
        elif line.strip():
            rows.append(f"<p>{html.escape(line)}</p>")
    if in_table:
        rows.append("</table>")
    body = "\n".join(rows)
    extra = []
    mes = _load(results / "mes" / "trace_summary.json")
    if mes:
        prim = mes["primary"]
        mode = "detector" if "detector" in prim else "simulated"
        scr = results / "mes" / f"screen_seed{mes['primary_seed']}_{mode}.csv"
        if scr.exists():
            df = pd.read_csv(scr).head(15)[["candidate", "n_exposed", "fail_exposed", "rate_exposed",
                                            "rate_unexposed", "risk_ratio", "rr_lo", "rr_hi", "p_fisher", "q_bh"]]
            extra.append(f"<h2>Primary seed {mes['primary_seed']} ({mode} inspection): naive screen, top 15</h2>"
                         + _table(df))
            extra.append("<p>Selected after stratification (CMH, week strata): <b>"
                         + html.escape(", ".join(prim[mode]["score"]["selected"])) + "</b>. Ground truth: "
                         + html.escape(", ".join(mes["truth"])) + ".</p>")
        svg = _svg_weekly(results)
        if svg:
            extra.append("<h2>Weekly AOI FAIL rate for the two injected causes (primary seed)</h2>" + svg)
    sop_rows = results / "sop" / "sop_answers_hybrid.jsonl"
    if sop_rows.exists():
        df = pd.DataFrame([json.loads(x) for x in sop_rows.read_text(encoding="utf-8").splitlines() if x.strip()])
        extra.append("<h2>SOP assistant: every test question</h2>"
                     + _table(df[["id", "question", "answerable", "status", "correct", "answer"]]))
    page = f"""<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1"><title>mini-mes-quality report</title>
<style>
:root{{--bg:#fff;--fg:#1f2937;--muted:#6b7280;--line:#e5e7eb;--accent:#c2410c}}
@media (prefers-color-scheme:dark){{:root{{--bg:#111827;--fg:#e5e7eb;--muted:#9ca3af;--line:#374151}}}}
body{{background:var(--bg);color:var(--fg);font:14px/1.5 system-ui,sans-serif;max-width:1100px;margin:0 auto;padding:16px}}
table{{border-collapse:collapse;width:100%;margin:8px 0 20px;font-size:13px;display:block;overflow-x:auto}}
td,th{{border-bottom:1px solid var(--line);padding:4px 8px;text-align:left;vertical-align:top}}
h1{{font-size:22px}} h2{{font-size:16px;margin-top:28px}} .ref,.note{{color:var(--muted)}}
svg{{max-width:100%;height:auto;background:#fff}}
</style></head><body>
<h1>mini-mes-quality - results report</h1>
<p class=note>Personal portfolio project (October 2026, built with AI assistance). MES data, SOP documents and the
image-to-unit mapping are SYNTHETIC. Images are from the public VisA dataset (CC BY 4.0) and are not included here.
No real factory, MES deployment or company is represented.</p>
{body}
{''.join(extra)}
</body></html>"""
    (results / "report.html").write_text(page, encoding="utf-8")


def write_all(results: Path, readme: Path) -> None:
    (results / "headline.json").write_text(json.dumps(headline(results), indent=2, sort_keys=True), encoding="utf-8")
    update_readme(readme, readme_block(results))
    write_html(results)
